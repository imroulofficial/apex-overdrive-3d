// Renders listening previews of the game's audio (engine through six gears,
// blow-off, nitro, drift, the race soundtrack, UI and race SFX, a full race mix) with the
// same modules the game plays live, and prints level stats for each clip.
//
//   npm i --no-save playwright && npx playwright install chromium   (once)
//   node tools/audio/render.mjs [clip names…]
//   node tools/audio/render.mjs --stall      frame-stall test and audio-thread cost (stall.js)
//   node tools/audio/render.mjs --live       live underrun test in a real AudioContext (stall.js)
//   node tools/audio/render.mjs --gates      audio-thread cost with and without idle layers unplugged
//   node tools/audio/render.mjs --compare    one scripted race, graph path vs car mixer (WAVs)
//   node tools/audio/render.mjs --soundtrack the race soundtrack for the car mixer (Opus + layout)
//
// Output: tools/audio/out/<clip>.wav
import { createServer } from 'vite';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const out = path.join(here, 'out');

let chromium;
try {
  const pw = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright');
  chromium = pw.chromium ?? pw.default.chromium;
} catch {
  console.error('Playwright is not installed: npm i --no-save playwright && npx playwright install chromium');
  process.exit(1);
}

const server = await createServer({ root, server: { port: 5198, strictPort: false }, logLevel: 'error' });
await server.listen();
// The live test needs audio to start without a gesture, and Chrome's playout (underrun) stats.
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required', '--enable-blink-features=AudioContextPlayoutStats'] });
let failed = false;
try {
  const page = await browser.newPage();
  page.on('pageerror', (e) => {
    failed = true;
    console.error('page error:', e.message);
  });
  await page.goto(`http://localhost:${server.config.server.port}/tools/audio/preview.html`);
  await page.waitForFunction(() => window.__audio, null, { timeout: 60000 });
  if (process.argv.includes('--live')) {
    // Synth: the synthesized car at the 32 kHz the Android build used to run at. Current: the
    // sampled car at the hardware's 48 kHz, as the Android build runs now. Previous: the graph
    // and control path from before the audio clock, for scale. Ballast stands in for the rest
    // of a phone's CPU load. Worklet: the car mixer (audio/carMixer.js), the build's race path now.
    for (const ballast of process.argv.includes('--ballast') ? [Number(process.argv[process.argv.indexOf('--ballast') + 1])] : [0.6, 0.75]) {
      for (const [path, latencyHint, rate] of [['previous', 'balanced', 48000], ['synth', 'playback', 32000], ['current', 'playback', 48000], ['worklet', 'playback', 48000]]) {
        const r = await page.evaluate((a) => window.__audio.live(a), { path, latencyHint, rate, ballast, seconds: 16 });
        console.log(`${path}, ballast ${ballast}: ${r.underruns} underruns (${r.underrunMs} ms of audio missing in ${r.playedSeconds} s played) · ${r.latencyHint} at ${r.sampleRate / 1000} kHz, buffer ${r.baseLatencyMs} ms, output latency ${r.outputLatencyMs} ms · one-shots peak ${r.voicesPeak} · per second ${r.perSecond.join(' ')}`);
      }
    }
    process.exit(0);
  }
  // What unplugging idle layers saves: the race graph with gates on the engine and the music,
  // and with either kept plugged in for the whole race.
  if (process.argv.includes('--gates')) {
    for (const gated of [{ engine: true, music: true }, { engine: false, music: true }, { engine: false, music: false }]) {
      const c = await page.evaluate((g) => window.__audio.cost('current', { rate: 48000, runs: 5, gated: g }), gated);
      console.log(`gates engine ${gated.engine ? 'on ' : 'off'} music ${gated.music ? 'on ' : 'off'}: ${c.renderMs} ms to render 24 s (${c.corePct}% of one core here)`);
    }
    process.exit(0);
  }
  // The race soundtrack for the car mixer: rendered here, encoded to Opus, its layout written
  // to src/audio/soundtrack.js (the game ships the file; nothing renders on the phone).
  if (process.argv.includes('--soundtrack')) {
    const r = await page.evaluate(() => window.__audio.soundtrack());
    await mkdir(out, { recursive: true });
    const wav = path.join(out, 'race-soundtrack-loop.wav');
    await writeFile(wav, Buffer.from(r.wav, 'base64'));
    const ogg = path.join(root, 'public/assets/audio/race-soundtrack.ogg');
    const { execFileSync } = await import('node:child_process');
    execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-i', wav, '-c:a', 'libopus', '-b:a', '128k', '-vbr', 'on', '-application', 'audio', ogg]);
    const info = { file: 'race-soundtrack.ogg', ...r.info };
    await writeFile(
      path.join(root, 'src/audio/soundtrack.js'),
      `// Generated by \`node tools/audio/render.mjs --soundtrack\` from audio/music.js: the race\n// soundtrack's layout in public/assets/audio/race-soundtrack.ogg (seconds), for the car mixer.\n// gain: the level the file was normalized from. start: the first note. drop: where the full\n// track starts (the green light jumps there at the next bar of the intro; the intro runs\n// into it otherwise). loopStart / loopEnd: the loop, its seam where two passes are most alike\n// (rho: how alike, for a constant-power crossfade). bar: one bar.\nexport const SOUNDTRACK = ${JSON.stringify(info)};\n`,
    );
    console.log(`soundtrack: ${r.info.seconds} s rendered in ${r.ms} ms -> ${ogg}`, info);
    process.exit(0);
  }
  // The same scripted race through the graph path and the car mixer: WAVs and RMS per second.
  if (process.argv.includes('--compare')) {
    await mkdir(out, { recursive: true });
    for (const p of ['current', 'worklet']) {
      const r = await page.evaluate((x) => window.__audio.compare(x), p);
      await writeFile(path.join(out, `race-sim-${p}.wav`), Buffer.from(r.wav, 'base64'));
      console.log(`${p}: peak ${r.stats.peakDb} dBFS, rms ${r.stats.rmsDb} dBFS · per second ${r.perSecond.join(' ')}`);
    }
    process.exit(failed ? 1 : 0);
  }
  if (process.argv.includes('--stall')) {
    for (const [path, profile] of [['previous', 'normal'], ['current', 'normal'], ['worklet', 'normal'], ['previous', 'heavy'], ['current', 'heavy'], ['worklet', 'heavy']]) {
      const r = await page.evaluate((a) => window.__audio.simulate(a), { path, profile, rate: 48000 });
      console.log(`${path}, ${profile} hitches: ${r.hitches} hitches plus 30 FPS frames (${r.hitchMs} ms of long frames, longest ${r.longestMs} ms)`);
      console.log(`  engine held without controls ${r.engineFrozenMs} ms (worst ${r.engineWorstFreezeMs} ms) · music 16ths dropped ${r.musicDropped}, queued late ${r.musicLate}`);
      console.log(`  one-shots sounding at once: peak ${r.voicesPeak}, stolen ${r.voicesStolen}, dropped ${r.voicesDropped} · peak ${r.peakDb} dBFS, non-finite ${r.nonFinite}`);
      if (r.nonFinite) failed = true;
    }
    // The synthesized car at the 32 kHz the Android build used to run at, and at 48 kHz; the
    // sampled car at the hardware rates the build runs at now.
    for (const [path, rate] of [['previous', 48000], ['synth', 32000], ['synth', 48000], ['current', 48000], ['current', 44100], ['worklet', 48000], ['worklet', 44100]]) {
      const c = await page.evaluate(([p, r]) => window.__audio.cost(p, { rate: r }), [path, rate]);
      console.log(`audio-thread cost, ${path} at ${rate / 1000} kHz: ${c.renderMs} ms to render 24 s (${c.corePct}% of one core here)`);
    }
    process.exit(failed ? 1 : 0);
  }
  const names = process.argv.slice(2).length ? process.argv.slice(2) : await page.evaluate(() => window.__audio.names);
  await mkdir(out, { recursive: true });
  for (const name of names) {
    const r = await page.evaluate((n) => window.__audio.render(n), name);
    await writeFile(path.join(out, `${name}.wav`), Buffer.from(r.wav, 'base64'));
    const s = r.stats;
    console.log(`${name}: peak ${s.peakDb} dBFS, rms ${s.rmsDb} dBFS, non-finite ${s.nonFinite}, rendered in ${r.ms} ms`);
    console.log(`  limiter p99 ${s.limiterMaxDb} dB, busy ${s.limiterBusyPct}% · clipper ${s.clipperPct}% of samples (input peak ${s.clipInDb} dBFS) · <150 Hz ${s.lowPct}% of energy · peak/rms into limiter ${s.limIn} dBFS`);
    for (const line of r.log) console.log(`  ${line}`);
    if (r.stats.nonFinite) failed = true;
  }
} finally {
  await browser.close();
  await server.close();
}
process.exit(failed ? 1 : 0);
